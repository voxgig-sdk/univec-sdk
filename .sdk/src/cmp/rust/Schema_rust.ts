import {
  Content,
  File,
  cmp,
  entitySpecMap,
  optionSpec,
} from '@voxgig/sdkgen'


import {
  Model,
} from '@voxgig/apidef'


import {
  rustRawString,
} from './utility_rust'


const Schema = cmp(async function Schema(props: any) {
  const ctx$ = props.ctx$
  const target = props.target

  const model: Model = ctx$.model

  const optspec = optionSpec(model, target.name)
  const entityspec = entitySpecMap(model, target.name) || {}

  // Beside config.rs, in core, and for the same reason: core owns the
  // generated data, so nothing in utility or feature has to reach up for it.
  File({ name: 'schema.' + target.ext }, () => {

    Content(`// ${model.const.Name} SDK: generated schemas. Do not edit.
//
// Built from the model: \`main.kit.optspec\` and each feature's
// \`config.options\` for the option spec; entity \`fields{}.type\` for the
// entity specs.

use crate::utility::jsonparse::json_parse;
use crate::utility::voxgigstruct::Value;

const OPTSPEC_DATA: &str = ${rustRawString(JSON.stringify(optspec))};

const ENTITYSPEC_DATA: &str = ${rustRawString(JSON.stringify(entityspec))};

/// The option spec make_options validates client options against.
///
/// Unreachable on error: the constant is generated by a JSON serialiser and
/// never edited by hand. Panicking beats returning an empty spec, which would
/// validate everything and fail far from the cause.
pub fn make_optspec() -> Value {
    json_parse(OPTSPEC_DATA).expect("${model.const.Name}: embedded option spec is not valid JSON")
}

/// Per-entity data and request specs, keyed by entity name.
pub fn make_entityspec() -> Value {
    json_parse(ENTITYSPEC_DATA).expect("${model.const.Name}: embedded entity spec is not valid JSON")
}

// SHARED SPECS, the shape core::config::shared_config uses and for the same
// reasons: the spec is read on every client construction and never mutated,
// so a per-call parse would be pure waste — and THREAD-LOCAL rather than
// global, because Value is Rc/RefCell-backed and so is neither Send nor Sync.
// The clone is an Rc bump, not a deep copy.
//
// The returned Value SHARES its nodes: treat it as read-only. make_options
// validates AGAINST the spec and writes into the options, never into the spec.
thread_local! {
    static SHARED_OPTSPEC: Value = make_optspec();
    static SHARED_ENTITYSPEC: Value = make_entityspec();
}

/// The per-thread option spec, built once on first use.
pub fn optspec() -> Value {
    SHARED_OPTSPEC.with(|s| s.clone())
}

/// The per-thread entity specs, built once on first use.
pub fn entityspec() -> Value {
    SHARED_ENTITYSPEC.with(|s| s.clone())
}
`)
  })
})


export {
  Schema
}
